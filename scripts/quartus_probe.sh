#!/usr/bin/env bash
# Quartus probe compile of one module (MAX 10 10M50DAF484C7G), run from WSL.
#
# Quartus is a Windows program and handles \\wsl$ paths poorly, so the sources are copied to a
# Windows build directory, a Tcl script is generated there from the template below, the Windows
# Quartus binaries are run in that directory, and the reports are copied back.
#
# Usage: scripts/quartus_probe.sh [options] <top> <file.sv> [<file.sv> ...]
#   --fit                    also run the Fitter and the Timing Analyzer (default: A&S only)
#   --clock NAME:PERIOD_NS   create_clock on top-level port NAME (written to a .sdc)
#   --virtual-pins           make every i_*/o_* port and rst a virtual pin (clock stays a pin)
#   --param NAME=VALUE       top-level parameter (repeatable; quote string values yourself)
#   --copy FILE              extra file copied next to the sources, e.g. an init file
#   --out DIR                where reports are copied (default: sim_build/quartus/<top>)
# Environment:
#   QUARTUS_ROOT       Quartus install (default /mnt/c/intelFPGA_lite/22.1std/quartus)
#   QUARTUS_BUILD_DIR  Windows-side build root (default: <Windows user profile>/fpga_build)
# Exit status: 0 success, 1 Quartus reported a failure, 2 Quartus not available (callers SKIP).
set -euo pipefail

QUARTUS_ROOT="${QUARTUS_ROOT:-/mnt/c/intelFPGA_lite/22.1std/quartus}"
QSH="$QUARTUS_ROOT/bin64/quartus_sh.exe"
QSTA="$QUARTUS_ROOT/bin64/quartus_sta.exe"
FAMILY="MAX 10"
DEVICE="10M50DAF484C7G"

fit=0
clock=""
virtual=0
params=()
copies=()
out=""
while [ "$#" -gt 0 ]; do
  case "$1" in
    --fit) fit=1; shift ;;
    --clock) clock="$2"; shift 2 ;;
    --virtual-pins) virtual=1; shift ;;
    --param) params+=("$2"); shift 2 ;;
    --copy) copies+=("$2"); shift 2 ;;
    --out) out="$2"; shift 2 ;;
    -h|--help) sed -n '2,20p' "$0"; exit 0 ;;
    *) break ;;
  esac
done
if [ "$#" -lt 2 ]; then
  echo "usage: $0 [options] <top> <file.sv>..." >&2
  exit 1
fi
top="$1"; shift
srcs=("$@")

if [ ! -x "$QSH" ] && [ ! -f "$QSH" ]; then
  echo "quartus_probe: Quartus not found at $QSH" >&2
  exit 2
fi

repo="$(cd "$(dirname "$0")/.." && pwd)"
out="${out:-$repo/sim_build/quartus/$top}"
if [ -z "${QUARTUS_BUILD_DIR:-}" ]; then
  win_profile="$(cd /mnt/c && cmd.exe /c 'echo %USERPROFILE%' 2>/dev/null | tr -d '\r')"
  QUARTUS_BUILD_DIR="$(wslpath "$win_profile")/fpga_build"
fi
work="$QUARTUS_BUILD_DIR/probe_$top"
rm -rf "$work"
mkdir -p "$work" "$out"
for f in "${srcs[@]}" "${copies[@]}"; do
  cp "$f" "$work/"
done

proj="probe_$top"
clock_port="${clock%%:*}"
clock_period="${clock#*:}"

# ------------------------------------------------------------------ Tcl template
{
  echo "# Generated by scripts/quartus_probe.sh"
  echo "load_package flow"
  echo "project_new $proj -overwrite"
  echo "set_global_assignment -name FAMILY \"$FAMILY\""
  echo "set_global_assignment -name DEVICE $DEVICE"
  echo "set_global_assignment -name TOP_LEVEL_ENTITY $top"
  echo "# MAX 10 initializes M9K contents only in this configuration mode (docs/decisions.md D-021)."
  echo "set_global_assignment -name INTERNAL_FLASH_UPDATE_MODE \"SINGLE IMAGE WITH ERAM\""
  echo "set_global_assignment -name NUM_PARALLEL_PROCESSORS 4"
  for f in "${srcs[@]}"; do
    echo "set_global_assignment -name SYSTEMVERILOG_FILE $(basename "$f")"
  done
  for p in "${params[@]}"; do
    echo "set_parameter -name ${p%%=*} {${p#*=}}"
  done
  if [ -n "$clock" ]; then
    echo "set_global_assignment -name SDC_FILE $proj.sdc"
  fi
  if [ "$virtual" -eq 1 ]; then
    # Port naming convention: inputs i_*, outputs o_*, plus rst. The clock is not matched, so
    # it stays a real pin on a global clock network. (A "-to *" wildcard with a clock override
    # made the clock virtual too.)
    echo "set_instance_assignment -name VIRTUAL_PIN ON -to i_*"
    echo "set_instance_assignment -name VIRTUAL_PIN ON -to o_*"
    echo "set_instance_assignment -name VIRTUAL_PIN ON -to rst"
  fi
  echo "execute_module -tool map"
  if [ "$fit" -eq 1 ]; then
    echo "execute_module -tool fit"
    echo "execute_module -tool sta"
  fi
  echo "project_close"
} > "$work/$proj.tcl"

if [ -n "$clock" ]; then
  {
    echo "create_clock -name $clock_port -period $clock_period [get_ports {$clock_port}]"
    echo "derive_clock_uncertainty"
  } > "$work/$proj.sdc"
fi

{
  echo "# Worst-case timing detail (slow corner) for the probe"
  echo "project_open $proj"
  echo "create_timing_netlist"
  echo "read_sdc"
  echo "update_timing_netlist"
  echo "report_timing -setup -npaths 1 -detail full_path -file timing_setup_worst.rpt"
  echo "report_timing -hold -npaths 1 -detail full_path -file timing_hold_worst.rpt"
  echo "create_timing_summary -setup -file timing_summary_setup.rpt"
  echo "create_timing_summary -hold -file timing_summary_hold.rpt"
  echo "report_clock_fmax_summary -file fmax.rpt"
  echo "delete_timing_netlist"
  echo "project_close"
} > "$work/sta_detail.tcl"

# ------------------------------------------------------------------ run
status=0
(cd "$work" && "$QSH" -t "$proj.tcl" > quartus_sh.log 2>&1) || status=1
if [ "$status" -eq 0 ] && [ "$fit" -eq 1 ] && [ -n "$clock" ]; then
  (cd "$work" && "$QSTA" -t sta_detail.tcl > quartus_sta_detail.log 2>&1) || status=1
fi

# ------------------------------------------------------------------ collect
for f in "$proj.tcl" "$proj.sdc" sta_detail.tcl "$proj.map.summary" "$proj.fit.summary" \
         "$proj.sta.summary" timing_setup_worst.rpt timing_hold_worst.rpt \
         timing_summary_setup.rpt timing_summary_hold.rpt fmax.rpt; do
  [ -f "$work/$f" ] && cp "$work/$f" "$out/"
done
grep -hE "^(Error|Warning) \(" "$work/quartus_sh.log" | sed 's/ File: .*//' > "$out/messages.txt" || true
grep -hE "was (un)?successful" "$work/quartus_sh.log" >> "$out/messages.txt" || true

echo "quartus_probe: $top -> $out ($( [ "$status" -eq 0 ] && echo success || echo FAILED ))"
exit "$status"
