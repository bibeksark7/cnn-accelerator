#!/usr/bin/env python3
"""SoC speedup report: the software CNN against the accelerator on PicoRV32 (spec §13.9, D-044).

1. Records the provenance of the measurement before simulating: commit, HEAD:rtl, HEAD:firmware,
   the PicoRV32 commit, whether the working tree was clean, and the Verilator version.
2. Runs testbench/system/test_soc.py::test_soc_bench with BENCH_IMAGES images: the bench firmware
   times, with rdcycle on the CPU, the software CNN, the image upload through the buffer window and
   the accelerator end to end, and the test checks both sets of logits against the golden model.
   The firmware is built by the test, and its compiler version is recorded.
3. Writes testbench/reports/soc_speedup.{json,md}.

Every number is a cycle count of the RTL simulation of the whole SoC (cycle-accurate for the
RTL); times assume the 50 MHz board clock, at which the SoC build closes timing
(fpga/de10lite_soc/reports/).

Besides the measured speedups, the report gives an instruction-count bound: the software CNN's
retired instructions divided by the accelerator's cycles, i.e. the speedup against an ideal core
that retires one instruction per cycle at the same clock (same instructions, no memory stalls).
It separates what the accelerator gains from what PicoRV32's 7-8 cycles per instruction add.

Usage: scripts/soc_speedup.py [--images N] [--from-results]
  --from-results  rebuild the reports from the last run's results without simulating
Run locally (the software CNN takes minutes of simulation per image); the full CI job runs one
image.
"""

from __future__ import annotations

import argparse
import json
import os
import statistics
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "sim_build" / "soc_speedup"
REPORTS = ROOT / "testbench" / "reports"
CLOCK_MHZ = 50.0


def git(*args: str) -> str:
    return subprocess.run(
        ["git", *args], cwd=ROOT, capture_output=True, text=True, check=True
    ).stdout.strip()


def provenance() -> dict:
    verilator = subprocess.run(["verilator", "--version"], capture_output=True, text=True).stdout
    return {
        "commit": git("rev-parse", "HEAD"),
        "rtl_tree": git("rev-parse", "HEAD:rtl"),
        "firmware_tree": git("rev-parse", "HEAD:firmware"),
        "picorv32_commit": git("rev-parse", "HEAD:third_party/picorv32"),
        "tree_clean": git("status", "--porcelain") == "",
        "verilator": verilator.strip(),
    }


def run(images: int) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "provenance.json").write_text(json.dumps(provenance(), indent=1))
    results = OUT / "results.json"
    results.unlink(missing_ok=True)
    env = {**os.environ, "BENCH_IMAGES": str(images), "TB_RESULTS": str(results)}
    cmd = [sys.executable, "-m", "pytest", "-q", "testbench/system/test_soc.py::test_soc_bench"]
    subprocess.run(cmd, cwd=ROOT, env=env, check=True)


def fmt(n: float) -> str:
    return f"{n:,.0f}"


def write_reports() -> None:
    prov = json.loads((OUT / "provenance.json").read_text())
    res = json.loads((OUT / "results.json").read_text())
    toolchain = (ROOT / "sim_build" / "firmware" / "bench" / "toolchain.txt").read_text().strip()
    rows = res["images"]
    for r in rows:
        r["speedup_end_to_end"] = r["software"] / r["end_to_end"]
        r["speedup_with_upload"] = r["software"] / (r["upload"] + r["end_to_end"])
        r["ipc1_bound_end_to_end"] = r["software_instret"] / r["end_to_end"]
        r["ipc1_bound_with_upload"] = r["software_instret"] / (r["upload"] + r["end_to_end"])
    keys = ("software", "software_instret", "upload", "end_to_end", "cyc_total")
    mean = {k: statistics.fmean(r[k] for r in rows) for k in keys}
    summary = {
        "images": len(rows),
        "clock_mhz": CLOCK_MHZ,
        "mean_cycles": mean,
        "speedup_end_to_end": mean["software"] / mean["end_to_end"],
        "speedup_with_upload": mean["software"] / (mean["upload"] + mean["end_to_end"]),
        "speedup_vs_cyc_total": mean["software"] / mean["cyc_total"],
        # Speedup against an ideal core retiring one instruction per cycle at the same clock.
        "ipc1_bound_end_to_end": mean["software_instret"] / mean["end_to_end"],
        "ipc1_bound_with_upload": mean["software_instret"] / (mean["upload"] + mean["end_to_end"]),
        "software_cpi": mean["software"] / mean["software_instret"],
    }
    data = {
        "script": "scripts/soc_speedup.py",
        "summary": summary,
        "per_image": rows,
        "firmware_compiler": toolchain,
        "provenance": prov,
    }
    (REPORTS / "soc_speedup.json").write_text(json.dumps(data, indent=1) + "\n")
    ms = 1e3 / (CLOCK_MHZ * 1e6)
    lines = [
        "# SoC speedup: software CNN vs. accelerator on PicoRV32",
        "",
        f"Generated by `scripts/soc_speedup.py` from the bench firmware (`firmware/apps/bench`) "
        f"running on the RTL simulation of the whole SoC (`soc_top`, Verilator), "
        f"{len(rows)} quick-subset image(s). Cycle counts are the CPU's `rdcycle` (spec §13.9). "
        f"Both the software CNN's and the accelerator's logits equal the golden model's for "
        f"every image. Times assume the 50 MHz board clock.",
        "",
        f"Firmware compiler: {toolchain}, `-O2`, RV32IM; PicoRV32 with the fast multiplier "
        "(spec §13.2).",
        "",
        f"The software CNN retires {fmt(mean['software_instret'])} instructions per image at "
        f"{summary['software_cpi']:.2f} cycles per instruction. PicoRV32 is a multi-cycle core "
        "without caches: every instruction fetch and data access is an AXI4-Lite transaction to "
        "the RAM. The speedup is that of this SoC with and without its accelerator; a CPU with "
        "tightly coupled memory or caches would run the software faster.",
        "",
        "| Measurement (mean per image) | Cycles | Time at 50 MHz |",
        "|---|---|---|",
        f"| Software CNN | {fmt(mean['software'])} | {mean['software'] * ms:.2f} ms |",
        f"| Accelerator, end to end (IMG_SEL, START, poll, read results) | "
        f"{fmt(mean['end_to_end'])} | {mean['end_to_end'] * ms:.3f} ms |",
        f"| Image upload through the buffer window (784 bytes) | {fmt(mean['upload'])} | "
        f"{mean['upload'] * ms:.3f} ms |",
        f"| Accelerator core (CYC_TOTAL) | {fmt(mean['cyc_total'])} | "
        f"{mean['cyc_total'] * ms:.3f} ms |",
        "",
        "| Speedup | Measured on PicoRV32 | Against an ideal 1-instruction-per-cycle core |",
        "|---|---|---|",
        f"| Software / accelerator end to end | {summary['speedup_end_to_end']:.1f}x | "
        f"{summary['ipc1_bound_end_to_end']:.1f}x |",
        f"| Software / (upload + end to end) | {summary['speedup_with_upload']:.1f}x | "
        f"{summary['ipc1_bound_with_upload']:.1f}x |",
        "",
        "Measured: the software CNN's cycles on PicoRV32 divided by the accelerator's. Against an "
        "ideal 1-instruction-per-cycle core: the software CNN's retired instructions "
        f"({fmt(mean['software_instret'])}) divided by the same accelerator cycles (as measured "
        "here, with PicoRV32 driving the upload and the polling), i.e. the speedup over a core at "
        "the same clock that runs the same instructions at one per cycle with no memory stalls. "
        "That bound is what remains of the speedup without PicoRV32's "
        f"{summary['software_cpi']:.2f} cycles per instruction.",
        "",
        "| Image | Software | Upload | End to end | CYC_TOTAL | Speedup (end to end) |",
        "|---|---|---|---|---|---|",
        *(
            f"| {r['image']} | {fmt(r['software'])} | {fmt(r['upload'])} | "
            f"{fmt(r['end_to_end'])} | {fmt(r['cyc_total'])} | {r['speedup_end_to_end']:.1f}x |"
            for r in rows
        ),
        "",
        f"Provenance: commit `{prov['commit'][:12]}`, RTL tree `{prov['rtl_tree'][:12]}`, "
        f"firmware tree `{prov['firmware_tree'][:12]}`, PicoRV32 `{prov['picorv32_commit'][:12]}`,"
        f" clean tree: {prov['tree_clean']}; {prov['verilator']}.",
        "",
    ]
    (REPORTS / "soc_speedup.md").write_text("\n".join(lines))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--images", type=int, default=4)
    ap.add_argument("--from-results", action="store_true")
    args = ap.parse_args()
    if not args.from_results:
        run(args.images)
    write_reports()
    print((REPORTS / "soc_speedup.md").read_text())
    return 0


if __name__ == "__main__":
    sys.exit(main())
