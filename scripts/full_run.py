#!/usr/bin/env python3
"""Full-network run of accel_top on MNIST test images, and the reports built from it.

1. Builds the input vectors from the MNIST test set in the git-ignored data/ cache (hardware
   input q = pixel >> 1) and the golden logits (model/golden.py), into sim_build/full_run/.
2. Runs testbench/system/test_accel_top.py in TB_MODE=full on Verilator, with every assertion
   bound, in its own build directory. The test loads the images through the memory port 16 at
   a time, runs them back to back with IMG_SEL (weights loaded once, from the init files) and
   writes one JSON line per image: logits match, RESULT, STATUS and every performance counter.
3. Writes, from those lines:
     testbench/reports/full_run.{json,md}      logit match and hardware accuracy
     testbench/reports/perf_counters.{json,md} per-image counters and derived throughput

Usage: scripts/full_run.py [--images N] [--start I] [--from-results]
  --from-results  rebuild the reports from the last run's JSON lines without simulating
Needs data/mnist.npz (python -m model.train or model.data downloads it). Never run in CI.
Exit status: 0 if every image's logits match the golden model, 1 otherwise.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT), str(ROOT / "testbench"), str(ROOT / "testbench" / "system")]

from model import data, golden, net  # noqa: E402

WORK = ROOT / "sim_build" / "full_run"
REPORTS = ROOT / "testbench" / "reports"
CLOCK_MHZ = 50.0  # the DE10-Lite clock the design is timed at (docs/decisions.md D-024)
LAYER_NAMES = [layer.name for layer in net.LAYERS]


def build_vectors(start: int, count: int) -> Path:
    mnist = data.load_mnist()
    x = mnist["test_x"][start : start + count]
    y = mnist["test_y"][start : start + count]
    q = data.to_hw_input(x)
    logits = golden.infer_batched(golden.QuantParams.load(), q)
    WORK.mkdir(parents=True, exist_ok=True)
    path = WORK / "vectors.npz"
    np.savez(path, q=q, logits=logits, label=y, index=np.arange(start, start + len(q)))
    return path


def simulate(vectors: Path, results: Path) -> None:
    import test_accel_top as t

    from common.runner import run_cocotb

    run_cocotb(
        sim="verilator",
        toplevel="accel_top",
        sources=t.RTL_SOURCES + t.SVA_SOURCES,
        test_module="test_accel_top",
        parameters=t.init_params(),
        extra_build_args=["--assert"],
        testcase="test_full_run",
        extra_env={"TB_MODE": "full", "TB_VECTORS": str(vectors), "TB_RESULTS": str(results)},
        log_file=WORK / "sim.log",
        build_tag="full_run",
    )


def stats(values: list[int]) -> dict[str, float | int]:
    a = np.array(values, dtype=np.int64)
    return {"min": int(a.min()), "max": int(a.max()), "mean": float(a.mean())}


def write_reports(recs: list[dict], seconds: float | None) -> bool:
    n = len(recs)
    match = sum(r["logits_match"] for r in recs)
    ok_status = sum(r["status"] == (2 | 5 << 8) for r in recs)  # DONE, last layer 5
    hw_correct = sum(r["result"] == r["label"] for r in recs)
    gold_correct = sum(r["golden_pred"] == r["label"] for r in recs)
    result_is_golden = sum(r["result"] == r["golden_pred"] for r in recs)
    quant = json.loads((ROOT / "model" / "reports" / "quantize.json").read_text())
    first, last = recs[0]["index"], recs[-1]["index"]
    full = {
        "script": "scripts/full_run.py",
        "images": n,
        "test_set_indices": [first, last],
        "logits_bit_exact": match,
        "status_done_no_error": ok_status,
        "result_equals_golden_class": result_is_golden,
        "hardware_correct": hw_correct,
        "hardware_accuracy": hw_correct / n,
        "golden_accuracy_same_images": gold_correct / n,
        "golden_integer_accuracy_full_test_set": quant.get("int_test_accuracy"),
        "float_accuracy_full_test_set": quant.get("float_test_accuracy"),
        "mismatches": [r for r in recs if not r["logits_match"]][:20],
        "simulation_seconds": seconds,
    }
    (REPORTS / "full_run.json").write_text(json.dumps(full, indent=2) + "\n")
    verdict = "all logits bit-exact" if match == n else f"{n - match} IMAGES DIFFER"
    lines = [
        "# Full-network run (MNIST test set)",
        "",
        "Generated by `scripts/full_run.py`: `accel_top` on Verilator with every assertion bound,",
        "images loaded through the memory port 16 at a time and run back to back with IMG_SEL,",
        "weights loaded once from the init files. Each image's ten logits (LOGIT CSRs) are",
        "compared with `model/golden.py`; RESULT is compared with the label.",
        "",
        f"**{n:,} images (test-set indices {first} to {last}): {verdict}.**",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Images | {n:,} |",
        f"| Logits bit-exact vs golden model | {match:,} / {n:,} |",
        f"| STATUS = DONE, no error, last layer 5 | {ok_status:,} / {n:,} |",
        f"| RESULT = golden class | {result_is_golden:,} / {n:,} |",
        f"| Hardware accuracy (RESULT = label) | {hw_correct / n:.4f} ({hw_correct:,} / {n:,}) |",
        f"| Golden integer model, same images | {gold_correct / n:.4f} |",
    ]
    if quant.get("int_test_accuracy") is not None:
        lines.append(
            f"| Golden integer / float model, full test set (`model/reports/quantize.json`) | "
            f"{quant['int_test_accuracy']:.4f} / {quant['float_test_accuracy']:.4f} |"
        )
    if seconds is not None:
        lines.append(f"| Simulation wall time | {seconds / 60:.1f} min |")
    lines.append("")
    (REPORTS / "full_run.md").write_text("\n".join(lines))

    # Performance counters.
    counters = {
        k: stats([r[k] for r in recs]) for k in ("cyc_total", "cyc_mac", "buf_rd", "buf_wr")
    }
    layers = {name: stats([r["layer_cyc"][i] for r in recs]) for i, name in enumerate(LAYER_NAMES)}
    constant = all(v["min"] == v["max"] for v in [*counters.values(), *layers.values()])
    cyc = counters["cyc_total"]["mean"]
    perf = {
        "script": "scripts/full_run.py",
        "images": n,
        "clock_mhz": CLOCK_MHZ,
        "counters": counters,
        "layer_cyc": layers,
        "identical_for_every_image": constant,
        "sequencer_overhead_cycles": counters["cyc_total"]["mean"]
        - sum(v["mean"] for v in layers.values()),
        "time_per_inference_ms": cyc / (CLOCK_MHZ * 1e3),
        "inferences_per_second": CLOCK_MHZ * 1e6 / cyc,
        "mac_active_fraction": counters["cyc_mac"]["mean"] / cyc,
    }
    (REPORTS / "perf_counters.json").write_text(json.dumps(perf, indent=2) + "\n")

    def cell(v: dict) -> str:
        if v["min"] == v["max"]:
            return f"{v['min']:,}"
        return f"{v['min']:,} to {v['max']:,} (mean {v['mean']:,.1f})"

    lines = [
        "# Performance counters per inference",
        "",
        "Generated by `scripts/full_run.py` from the CSRs (spec §10.2) read after each image of",
        f"the full run ({n:,} MNIST test images, `testbench/reports/full_run.md`). Time and",
        f"throughput assume the {CLOCK_MHZ:.0f} MHz board clock (timing closes there, D-024).",
        "",
        "Every counter had the same value for every image."
        if constant
        else "**The counters differ between images** (range shown).",
        "",
        "| Counter | Per image |",
        "|---|---|",
        f"| CYC_TOTAL (START to DONE) | {cell(counters['cyc_total'])} |",
        f"| CYC_MAC (array consumed a reduction step) | {cell(counters['cyc_mac'])} |",
        f"| BUF_RD (IMG, ACT0, ACT1, WGT, PARAM reads) | {cell(counters['buf_rd'])} |",
        f"| BUF_WR (ACT0, ACT1 writes) | {cell(counters['buf_wr'])} |",
        "",
        "| Layer | LAYER_CYC |",
        "|---|---|",
        *[f"| {name} | {cell(v)} |" for name, v in layers.items()],
        f"| sequencer (CYC_TOTAL - sum of LAYER_CYC) | {perf['sequencer_overhead_cycles']:,.0f} |",
        "",
        "| Derived | Value |",
        "|---|---|",
        f"| Time per inference at {CLOCK_MHZ:.0f} MHz | {perf['time_per_inference_ms']:.3f} ms |",
        f"| Inferences per second at {CLOCK_MHZ:.0f} MHz | {perf['inferences_per_second']:,.0f} |",
        f"| MAC-active cycles / total cycles | {100 * perf['mac_active_fraction']:.1f} % |",
        "",
    ]
    (REPORTS / "perf_counters.md").write_text("\n".join(lines))
    return match == n and ok_status == n


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--images", type=int, default=10000)
    ap.add_argument("--start", type=int, default=0)
    ap.add_argument("--from-results", action="store_true")
    args = ap.parse_args()
    results = WORK / "results.jsonl"
    seconds = None
    if not args.from_results:
        vectors = build_vectors(args.start, args.images)
        t0 = time.time()
        try:
            simulate(vectors, results)
        except AssertionError as e:  # mismatching logits: still write the reports
            print(f"simulation reported a failure: {e}", file=sys.stderr)
        seconds = time.time() - t0
    recs = [json.loads(line) for line in results.read_text().splitlines() if line.strip()]
    if not recs:
        print("no results", file=sys.stderr)
        return 1
    ok = write_reports(recs, seconds)
    print((REPORTS / "full_run.md").read_text())
    print((REPORTS / "perf_counters.md").read_text())
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
