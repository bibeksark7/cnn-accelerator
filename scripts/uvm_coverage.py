#!/usr/bin/env python3
"""Merge and report the UVM bench's functional coverage (testbench/uvm, accel_coverage.svh).

Input: Verilator --coverage-user files (coverage.dat, one per UVM test). Each covergroup bin is a
line `C '<fields>' <count>`; the fields include the bin's hierarchical name (h), its type
(Bt=ignore / illegal: not a goal) and option.at_least (s, default 1). Counts are summed over the
files; a bin is met when its merged count reaches at_least.

Goal: every bin met, except the documented gaps in GAPS (each with the reason it cannot be or is
not hit); a listed gap that is in fact met is reported, so the list stays honest.

Usage (from the repository root; testbench/uvm/test_uvm.py writes the .dat files):
  scripts/uvm_coverage.py --out testbench/reports/uvm_coverage.md sim_build/uvm/coverage/*.dat
Exit status: 0 if the goal is met, 1 otherwise.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# Bin (hierarchical name, as reported: covergroup.coverpoint.bin) -> why it is a documented gap.
GAPS: dict[str, str] = {}

LINE_RE = re.compile(r"^C '(?P<fields>[^']*)' (?P<count>\d+)$")


@dataclass
class Bin:
    name: str  # covergroup.coverpoint.bin
    group: str
    count: int
    at_least: int


def parse_fields(raw: str) -> dict[str, str]:
    out = {}
    for item in raw.split("\x01"):
        if "\x02" in item:
            k, v = item.split("\x02", 1)
            out[k] = v
    return out


def merge(files: list[Path]) -> dict[str, Bin]:
    """Goal bins (ignore / illegal bins dropped) with counts summed over `files`."""
    bins: dict[str, Bin] = {}
    for f in files:
        for line in f.read_text(errors="replace").splitlines():
            m = LINE_RE.match(line)
            if not m:
                continue
            fields = parse_fields(m["fields"])
            if fields.get("t") != "covergroup" or fields.get("Bt") in ("ignore", "illegal"):
                continue
            full = fields["h"]  # e.g. accel_pkg::accel_coverage::cg_csr.x_reg_we.<auto_0,auto_1>
            name = full.split("::")[-1]
            group = name.split(".")[0]
            b = bins.setdefault(name, Bin(name, group, 0, int(fields.get("s", "1"))))
            b.count += int(m["count"])
    return bins


@dataclass
class Report:
    ok: bool
    summary: str
    text: str


def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True).stdout.strip()


def report(bins: dict[str, Bin], tests: list[str], seeds: str = "") -> Report:
    groups: dict[str, list[Bin]] = {}
    for b in sorted(bins.values(), key=lambda b: b.name):
        groups.setdefault(b.group, []).append(b)
    met = [b for b in bins.values() if b.count >= b.at_least]
    unmet = [b for b in bins.values() if b.count < b.at_least]
    gaps = [b for b in unmet if b.name in GAPS]
    missing = [b for b in unmet if b.name not in GAPS]
    stale_gaps = sorted(g for g in GAPS if g in bins and bins[g].count >= bins[g].at_least)
    unknown_gaps = sorted(g for g in GAPS if g not in bins)
    ok = bool(bins) and not missing and not stale_gaps and not unknown_gaps
    summary = (
        f"{len(bins)} bins, {len(met)} met, {len(gaps)} documented gaps, "
        f"{len(missing)} missing" + ("" if ok else " (goal NOT met)")
    )
    clean = git("status", "--porcelain", "--untracked-files=no") == ""
    lines = [
        "# UVM functional coverage",
        "",
        "Generated by `scripts/uvm_coverage.py` from the coverage of every UVM test "
        "(`testbench/uvm/test_uvm.py`, Verilator `--coverage-user`), counts summed over the tests.",
        "Goal: every bin met, or listed below as a documented gap with its reason.",
        "",
        f"- Result: **{summary}**",
        f"- Tests: {', '.join(tests)}",
        *([f"- Seeds: {seeds}"] if seeds else []),
        f"- Commit: `{git('rev-parse', 'HEAD')}` (tree {'clean' if clean else 'DIRTY'})",
        f"- RTL tree: `{git('rev-parse', 'HEAD:rtl')}`; UVM bench tree: "
        f"`{git('rev-parse', 'HEAD:testbench/uvm')}`; uvm-core: "
        f"`{git('rev-parse', 'HEAD:third_party/uvm-core')}`",
        "",
        "| Covergroup | Bins | Met | Not met |",
        "|---|---|---|---|",
    ]
    for g, bs in groups.items():
        not_met = [b.name.split(".", 1)[1] for b in bs if b.count < b.at_least]
        lines.append(
            f"| `{g}` | {len(bs)} | {sum(b.count >= b.at_least for b in bs)} | "
            f"{', '.join(f'`{n}`' for n in not_met) or '—'} |"
        )
    lines += ["", "## Documented gaps", ""]
    if GAPS:
        lines += [f"- `{name}`: {why}" for name, why in sorted(GAPS.items())]
    else:
        lines.append("None.")
    if missing or stale_gaps or unknown_gaps:
        lines += ["", "## Goal not met", ""]
        lines += [f"- missing: `{b.name}` ({b.count}/{b.at_least})" for b in missing]
        lines += [f"- listed as a gap but met: `{g}`" for g in stale_gaps]
        lines += [f"- listed as a gap but no such bin: `{g}`" for g in unknown_gaps]
    lines += ["", "## Every bin", "", "| Bin | Hits |", "|---|---|"]
    lines += [f"| `{b.name}` | {b.count} |" for b in sorted(bins.values(), key=lambda b: b.name)]
    return Report(ok, summary, "\n".join(lines) + "\n")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("files", nargs="+", type=Path)
    ap.add_argument("--out", type=Path, help="write the Markdown report here")
    a = ap.parse_args()
    r = report(merge(a.files), [f.stem for f in a.files])
    if a.out:
        a.out.write_text(r.text)
    print(r.summary)
    return 0 if r.ok else 1


if __name__ == "__main__":
    sys.exit(main())
