#!/usr/bin/env python3
"""Generate firmware C sources from the committed model artifacts (docs/decisions.md D-044).

  gen_data.py params <out_dir>
      net_params.h / net_params.c: the integer network (model/artifacts/params.npz) for the
      software CNN: int8 weights in the golden model's layouts, int32 biases, M and S.
  gen_data.py images <out_dir> <set> [<count>]
      images.h / images.c: `count` int8 input images (q bytes, 28x28 row-major) from
      model/artifacts/quick_subset.npz (set "quick") or saturation_subset.npz ("saturation").
  gen_data.py labels <out_dir>
      labels.h / labels.c: the true labels of the 16 preloaded IMG slots
      (model/artifacts/mem/demo.json, the images the board build preloads, spec 12).

Nothing generated is committed; the Makefile writes it next to the build outputs.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
ARTIFACTS = ROOT / "model" / "artifacts"
HEADER = "/* Generated by firmware/tools/gen_data.py from model/artifacts; do not edit. */\n"


def _init(values: np.ndarray, per_line: int, indent: int) -> str:
    """Brace-nested initializer for an N-d array (innermost rows `per_line` values per line)."""
    pad = "  " * indent
    if values.ndim == 1:
        flat = [str(int(v)) for v in values]
        rows = [", ".join(flat[i : i + per_line]) for i in range(0, len(flat), per_line)]
        if len(rows) == 1:
            return "{" + rows[0] + "}"
        inner = ",\n".join(f"{pad}  {r}" for r in rows)
        return "{\n" + inner + f"\n{pad}}}"
    parts = ",\n".join(f"{pad}  " + _init(v, per_line, indent + 1) for v in values)
    return "{\n" + parts + f"\n{pad}}}"


def c_array(ctype: str, name: str, values: np.ndarray, per_line: int = 16) -> str:
    arr = np.asarray(values)
    dims = "".join(f"[{d}]" for d in arr.shape)
    return f"const {ctype} {name}{dims} = {_init(arr, per_line, 0)};\n"


def gen_params(out: Path) -> None:
    with np.load(ARTIFACTS / "params.npz") as f:
        p = {k: f[k] for k in f}
    decls = []
    body = [HEADER, '#include "net_params.h"\n\n']
    for name, ctype in (
        ("conv1_w", "int8_t"), ("conv1_b", "int32_t"), ("conv1_m", "uint16_t"),
        ("conv1_s", "uint8_t"), ("conv2_w", "int8_t"), ("conv2_b", "int32_t"),
        ("conv2_m", "uint16_t"), ("conv2_s", "uint8_t"), ("fc_w", "int8_t"), ("fc_b", "int32_t"),
    ):  # fmt: skip
        arr = p[name]
        dims = "".join(f"[{d}]" for d in arr.shape)
        decls.append(f"extern const {ctype} {name}{dims};")
        body.append(c_array(ctype, name, arr) + "\n")
    hdr = [
        HEADER,
        "#ifndef NET_PARAMS_H\n#define NET_PARAMS_H\n\n#include <stdint.h>\n",
        "/* conv*_w: [C_out][3][3][C_in]; fc_w: [10][400] with columns in HWC order. */",
        *decls,
        "\n#endif\n",
    ]
    (out / "net_params.h").write_text("\n".join(hdr))
    (out / "net_params.c").write_text("".join(body))


def gen_images(out: Path, which: str, count: int | None) -> None:
    files = {"quick": "quick_subset.npz", "saturation": "saturation_subset.npz"}
    with np.load(ARTIFACTS / files[which]) as f:
        q = f["q"]
    if count is not None:
        q = q[:count]
    n = len(q)
    hdr = (
        HEADER
        + "#ifndef IMAGES_H\n#define IMAGES_H\n\n#include <stdint.h>\n\n"
        + f"#define NUM_IMAGES {n}u\n\n"
        + f"/* {which} set, images 0..{n - 1}: q bytes, 28x28 row-major. */\n"
        + "extern const int8_t images[NUM_IMAGES][784];\n\n#endif\n"
    )
    (out / "images.h").write_text(hdr)
    (out / "images.c").write_text(
        HEADER + '#include "images.h"\n\n' + c_array("int8_t", "images", q.reshape(n, 784), 28)
    )


def gen_labels(out: Path) -> None:
    import json

    labels = json.loads((ARTIFACTS / "mem" / "demo.json").read_text())["label"]
    (out / "labels.h").write_text(
        HEADER
        + "#ifndef LABELS_H\n#define LABELS_H\n\n#include <stdint.h>\n\n"
        + f"#define NUM_SLOTS {len(labels)}u\n\n"
        + "/* True label of IMG slot i (the preloaded demo images). */\n"
        + "extern const uint8_t slot_label[NUM_SLOTS];\n\n#endif\n"
    )
    (out / "labels.c").write_text(
        HEADER + '#include "labels.h"\n\n' + c_array("uint8_t", "slot_label", np.array(labels))
    )


def main(argv: list[str]) -> int:
    if len(argv) < 3 or argv[1] not in ("params", "images", "labels"):
        print(__doc__, file=sys.stderr)
        return 2
    out = Path(argv[2])
    out.mkdir(parents=True, exist_ok=True)
    if argv[1] == "params":
        gen_params(out)
    elif argv[1] == "labels":
        gen_labels(out)
    else:
        gen_images(out, argv[3], int(argv[4]) if len(argv) > 4 else None)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
